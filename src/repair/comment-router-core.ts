export function buildAutomergeSquashMessage({
  command,
  view,
  target,
  comments,
}: LooseRecord): LooseRecord {
  const number = Number(command.issue_number);
  const rawTitle = String(view.title ?? target.title ?? `PR #${number}`).trim();
  const subject = rawTitle.includes(`#${number}`) ? rawTitle : `${rawTitle} (#${number})`;
  const summaryLines = reviewSummaryLines(command);
  const fixupLines = automergeFixupLines({ view, comments });
  const validationLines = [
    `ClawSweeper review passed for head ${target.head_sha ?? command.expected_head_sha ?? "unknown"}.`,
    "Required merge gates passed before the squash merge.",
  ];
  const body = [
    "Summary:",
    ...summaryLines.map((line: string) => `- ${line}`),
    "",
    "Automerge notes:",
    ...fixupLines.map((line: string) => `- ${line}`),
    "",
    "Validation:",
    ...validationLines.map((line: string) => `- ${line}`),
    "",
    `Prepared head SHA: ${target.head_sha ?? command.expected_head_sha ?? "unknown"}`,
    ...(command.comment_url ? [`Review: ${command.comment_url}`] : []),
    "",
    ...automergeCreditTrailers({ command, comments, commits: view.commits ?? [] }),
  ].join("\n");
  return { subject, body: body.trimEnd(), summaryLines, fixupLines };
}

function reviewSummaryLines(command: LooseRecord): string[] {
  const lines = linesFromMarkdownSection(command.review_summary);
  if (lines.length > 0) return lines.slice(0, 4);
  return [
    `Merged ${command.target?.title ?? `PR #${command.issue_number}`} after ClawSweeper review.`,
  ];
}

function automergeFixupLines({ view, comments }: LooseRecord): string[] {
  const lines: string[] = [];
  const safeComments = Array.isArray(comments) ? comments : [];
  const commits = Array.isArray(view.commits) ? view.commits : [];
  const sawRepair = safeComments.some((comment: JsonValue) =>
    String(comment.body ?? "").includes("clawsweeper_auto_repair"),
  );
  const sawFinding = safeComments.some((comment: JsonValue) =>
    /Codex review: found issues before merge|clawsweeper-action:fix-required/i.test(
      String(comment.body ?? ""),
    ),
  );
  if (sawRepair) lines.push("Ran the ClawSweeper repair loop before final review.");
  if (sawFinding) lines.push("Addressed earlier ClawSweeper review findings before merge.");
  const followupCommits = commits.slice(1).map(commitHeadline).filter(Boolean);
  const followupPrefix =
    sawRepair || sawFinding
      ? "Included post-review commit in the final squash"
      : "PR branch already contained follow-up commit before automerge";
  for (const headline of followupCommits.slice(0, 6)) {
    lines.push(`${followupPrefix}: ${headline}`);
  }
  const uniqueLines = unique(lines).slice(0, 8);
  return uniqueLines.length > 0
    ? uniqueLines
    : ["No ClawSweeper repair was needed after automerge opt-in."];
}

function automergeCreditTrailers({ command, comments, commits }: LooseRecord): string[] {
  const trailers: string[] = [];
  const coAuthorKeys = new Set<string>();
  for (const trailer of coAuthorTrailersFromCommits(commits, coAuthorKeys)) {
    trailers.push(trailer);
  }

  const maintainer = maintainerCredit(
    command.maintainer_attribution ??
      automergeRequestedByFromComments(comments) ??
      automergeRequestedByFromBody(command.target?.body) ??
      command,
  );
  if (!maintainer) return trailers;
  trailers.push(`Approved-by: ${maintainer.login}`);
  return trailers;
}

export function automergeRequestedByFromComments(comments: JsonValue): LooseRecord | null {
  if (!Array.isArray(comments)) return null;
  const byId = new Map<string, LooseRecord>();
  for (const comment of comments) {
    const id = String(comment?.id ?? "").trim();
    if (id) byId.set(id, comment);
  }
  const candidates: Array<{ at: number; comment: LooseRecord }> = [];
  for (const statusComment of comments) {
    const body = String(statusComment?.body ?? "");
    for (const marker of body.matchAll(
      /<!--\s*clawsweeper-command:([^:\s>]+):(.+?):(automerge|maintainer_approve_automerge):([^>\s]+)\s*-->/gi,
    )) {
      const [, commentId, createdAt, intent] = marker;
      if (!["automerge", "maintainer_approve_automerge"].includes(String(intent))) continue;
      const original = byId.get(String(commentId ?? "").trim());
      if (!original || original === statusComment) continue;
      if (String(original?.user?.login ?? original?.author ?? "").includes("[bot]")) continue;
      const parsed = parseCommand(String(original?.body ?? ""));
      if (!["automerge", "maintainer_approve_automerge"].includes(String(parsed.intent))) continue;
      candidates.push({
        at: Date.parse(String(createdAt ?? original?.created_at ?? original?.createdAt ?? "")) || 0,
        comment: original,
      });
    }
  }
  const latest = candidates.sort((left, right) => right.at - left.at)[0]?.comment;
  const author = latest?.user?.login ?? latest?.author;
  if (!author) return null;
  return {
    author,
    author_id: latest?.user?.id ?? latest?.author_id ?? null,
    author_name: latest?.user?.name ?? latest?.author_name ?? null,
  };
}

function coAuthorTrailersFromCommits(commits: JsonValue, seen: Set<string>): string[] {
  if (!Array.isArray(commits)) return [];
  const trailers: string[] = [];
  for (const commit of commits) {
    for (const author of commit?.authors ?? []) {
      const name = String(author?.name ?? author?.login ?? "").trim();
      const email = String(author?.email ?? "").trim();
      if (!name || !email) continue;
      const key = coAuthorKey(name, email);
      if (key === clawsweeperCoAuthorKey() || seen.has(key)) continue;
      seen.add(key);
      trailers.push(`Co-authored-by: ${name} <${email}>`);
    }
  }
  return trailers;
}

function maintainerCredit(value: LooseRecord): LooseRecord | null {
  const login = normalizedLogin(value.author ?? value.login);
  if (!login || login.includes("[bot]")) return null;
  return {
    login,
  };
}

export function automergeRequestedByFromBody(body: JsonValue): LooseRecord | null {
  const attrs = automergeRequestedByAttributes(body);
  if (!attrs) return null;
  const author = attrs.login ?? attrs.author ?? attrs.requested_by;
  if (!author) return null;
  return {
    author,
    author_id: attrs.id ?? attrs.author_id ?? null,
    author_name: attrs.name ?? attrs.author_name ?? null,
  };
}

function commitHeadline(commit: JsonValue): string {
  return compactText(commit?.messageHeadline ?? commit?.headline ?? commit?.message ?? "", 160);
}

function linesFromMarkdownSection(section: JsonValue): string[] {
  const text = String(section ?? "").trim();
  if (!text) return [];
  const bulletLines = text
    .split(/\n+/)
    .map((line: string) => line.replace(/^\s*[-*]\s+/, "").trim())
    .filter(Boolean);
  if (bulletLines.length > 1) return bulletLines.map((line) => compactText(line, 220));
  return [compactText(text, 320)];
}

function unique<T>(items: T[]): T[] {
  return [...new Set(items)];
}

export function reviewedHeadShaBlockReason({
  expectedHeadSha,
  currentHeadSha,
  markerName,
}: LooseRecord) {
  const marker = String(markerName ?? "review");
  if (!expectedHeadSha || expectedHeadSha === "unknown") {
    return `ClawSweeper ${marker} marker must include the reviewed PR head SHA`;
  }
  if (currentHeadSha && expectedHeadSha !== currentHeadSha) {
    return `ClawSweeper ${marker} marker targets a stale PR head SHA`;
  }
  return null;
}

export function trustedCloseBlockReason({
  repo,
  kind,
  labels,
  closeReason,
  closeConfidence,
  closeActionTaken,
  createdAt,
  expectedHeadSha,
  currentHeadSha,
  expectedItemUpdatedAt,
  currentItemUpdatedAt,
  expectedSourceRevision,
  currentSourceRevision,
  authorAssociation,
  reviewedAt,
  assignees,
  milestone,
  reactions,
  requestedReviewers,
  requestedTeams,
  comments,
  reviews,
  reviewComments,
  sourceCommentId,
  trustedAuthors = new Set(),
  now,
}: LooseRecord): string | null {
  const closeKind = normalizedCloseKind(kind);
  if (!closeKind) return "trusted close marker requires an issue or pull request target";
  const reason = String(closeReason ?? "").trim() as RepositoryCloseReason;
  if (!reason || reason === "none")
    return "trusted close marker must include an apply close reason";
  if (closeKind === "pull_request" || reason !== "unsponsored_feature_request") {
    const headBlock = reviewedHeadShaBlockReason({
      expectedHeadSha,
      currentHeadSha,
      markerName: "close",
    });
    if (headBlock) return headBlock;
  }
  const confidence = String(closeConfidence ?? "")
    .trim()
    .toLowerCase();
  if (confidence !== "high") {
    return `trusted close marker confidence must be high, got ${confidence || "unknown"}`;
  }
  const actionTaken = String(closeActionTaken ?? "").trim();
  if (actionTaken !== "proposed_close") {
    return `trusted close marker action_taken must be proposed_close, got ${actionTaken || "unknown"}`;
  }

  const profile = trustedCloseRepositoryProfile(repo);
  if (typeof profile === "string") return profile;
  if (!isAutoCloseAllowed(profile, closeKind, reason)) {
    return `${reason} is not allowed for ${profile.targetRepo} ${closeKind} apply policy`;
  }
  if (
    closeKind === "pull_request" &&
    reason === "unconfirmed_product_direction" &&
    !unconfirmedProductDirectionCloseEnabled()
  ) {
    return "unconfirmed product-direction apply policy is disabled";
  }
  if (
    closeKind === "issue" &&
    reason === "unsponsored_feature_request" &&
    !unsponsoredFeatureCloseEnabled()
  ) {
    return "unsponsored feature-request apply policy is disabled";
  }
  if (
    closeKind === "pull_request" &&
    reason === "author_pr_budget_exceeded" &&
    !authorPrBudgetCloseEnabled()
  ) {
    return "author PR-budget apply policy is disabled";
  }
  const reasonSpecificBlock = trustedCloseReasonSpecificBlockReason({
    reason,
    closeKind,
    createdAt,
    expectedItemUpdatedAt,
    reviewedAt,
    labels,
    assignees,
    milestone,
    reactions,
    requestedReviewers,
    requestedTeams,
    comments,
    reviews,
    reviewComments,
    now,
  });
  if (reasonSpecificBlock) {
    return reasonSpecificBlock;
  }

  const protectedLabels = trustedCloseBlockingProtectedLabels(labels, reason);
  if (protectedLabels.length > 0) return `protected label: ${protectedLabels.join(", ")}`;

  const normalizedAuthorAssociation = normalizeAuthorAssociation(authorAssociation);
  if (closeKind === "pull_request" && !isVerifiedFixedCloseReason(reason)) {
    if (MAINTAINER_AUTHOR_ASSOCIATIONS.has(normalizedAuthorAssociation)) {
      return `author association is ${normalizedAuthorAssociation}`;
    }
  }

  const updatedAtBlock = trustedCloseUpdatedAtBlockReason({
    expectedItemUpdatedAt,
    currentItemUpdatedAt,
    expectedSourceRevision,
    currentSourceRevision,
    comments,
    sourceCommentId,
    trustedAuthors,
  });
  if (updatedAtBlock) return updatedAtBlock;

  const activityBlock = nonAutomationActivityAfterReviewBlock({
    comments,
    reviewedAt,
    trustedAuthors,
  });
  if (activityBlock) return activityBlock;

  return null;
}

function trustedCloseReasonSpecificBlockReason({
  reason,
  closeKind,
  createdAt,
  expectedItemUpdatedAt,
  reviewedAt,
  labels,
  assignees,
  milestone,
  reactions,
  requestedReviewers,
  requestedTeams,
  comments,
  reviews,
  reviewComments,
  now,
}: LooseRecord): string | null {
  if (closeKind === "issue" && reason === "unsponsored_feature_request") {
    if (!isOlderThanDays(createdAt, UNSPONSORED_FEATURE_MIN_AGE_DAYS, Number(now) || Date.now())) {
      return `unsponsored_feature_request requires issue older than ${UNSPONSORED_FEATURE_MIN_AGE_DAYS} days`;
    }
    const normalized = normalizedLabels(labels);
    const securityLabel = normalized.find(
      (label) => label === "impact:security" || label === NEEDS_SECURITY_REVIEW_LABEL,
    );
    if (securityLabel) return `${securityLabel} blocks unsponsored feature auto-close`;
    if (normalized.includes("clawsweeper:linked-pr-open")) {
      return "clawsweeper:linked-pr-open blocks unsponsored feature auto-close";
    }
    if (nonEmptyArray(assignees)) return "assigned issue has maintainer engagement";
    if (milestone) return "milestoned issue has maintainer engagement";
    if (Number((reactions as LooseRecord | undefined)?.total_count ?? 0) >= 20) {
      return "issue has strong community traction (20 or more reactions)";
    }
    if (maintainerAssociatedEntries(comments).length > 0) {
      return "maintainer issue comment confirms engagement";
    }
    if (
      recentHumanComment(comments, UNSPONSORED_FEATURE_MIN_INACTIVE_DAYS, Number(now) || Date.now())
    ) {
      return `issue has a non-bot comment within the last ${UNSPONSORED_FEATURE_MIN_INACTIVE_DAYS} days`;
    }
    return null;
  }
  if (closeKind !== "pull_request") return null;
  if (reason === "author_pr_budget_exceeded") {
    return "author_pr_budget_exceeded closes require apply-decisions live author count, inactivity, and per-run-cap proof";
  }
  if (reason === "unconfirmed_product_direction") {
    const ageBlock = unconfirmedProductDirectionTrustedCloseAgeBlock({
      createdAt,
      expectedItemUpdatedAt,
      reviewedAt,
      now,
    });
    if (ageBlock) return ageBlock;
    const exemptLabel = normalizedLabels(labels).find((label) =>
      UNCONFIRMED_PRODUCT_DIRECTION_EXEMPT_LABELS.has(label),
    );
    if (exemptLabel) return `${exemptLabel} exempts this PR from product-direction auto-close`;
    const humanSignal = trustedCloseHumanSignalBlock({
      assignees,
      requestedReviewers,
      requestedTeams,
      comments,
      reviews,
      reviewComments,
      productDirection: true,
    });
    if (humanSignal) return humanSignal;
  }
  if (reason === "low_signal_unmergeable_pr") {
    const humanSignal = trustedCloseHumanSignalBlock({
      assignees,
      requestedReviewers,
      requestedTeams,
      comments,
      reviews,
      productDirection: false,
    });
    if (humanSignal) return humanSignal;
    return "low_signal_unmergeable_pr closes require apply-decisions live conflict and author-activity proof";
  }
  return null;
}

function recentHumanComment(comments: JsonValue, days: number, now: number): boolean {
  if (!Array.isArray(comments)) return true;
  return comments.some((entry) => {
    const comment = entry as LooseRecord;
    if ((comment.user as LooseRecord | undefined)?.type === "Bot") return false;
    return !isOlderThanDays(comment.created_at, days, now);
  });
}

function unconfirmedProductDirectionTrustedCloseAgeBlock({
  createdAt,
  expectedItemUpdatedAt,
  reviewedAt,
  now,
}: LooseRecord): string | null {
  if (
    !isOlderThanDays(
      createdAt,
      UNCONFIRMED_PRODUCT_DIRECTION_MIN_AGE_DAYS,
      Number(now) || Date.now(),
    )
  ) {
    return `unconfirmed_product_direction requires PR older than ${UNCONFIRMED_PRODUCT_DIRECTION_MIN_AGE_DAYS} days`;
  }
  const sourceUpdatedAtMs = Date.parse(String(expectedItemUpdatedAt ?? ""));
  const reviewedAtMs = Date.parse(String(reviewedAt ?? ""));
  if (
    !Number.isFinite(sourceUpdatedAtMs) ||
    !Number.isFinite(reviewedAtMs) ||
    reviewedAtMs - sourceUpdatedAtMs <= UNCONFIRMED_PRODUCT_DIRECTION_MIN_INACTIVE_DAYS * DAY_MS
  ) {
    return `unconfirmed_product_direction requires ${UNCONFIRMED_PRODUCT_DIRECTION_MIN_INACTIVE_DAYS} days without source activity before review`;
  }
  return null;
}

function trustedCloseHumanSignalBlock({
  assignees,
  requestedReviewers,
  requestedTeams,
  comments,
  reviews,
  reviewComments,
  productDirection,
}: LooseRecord): string | null {
  if (nonEmptyArray(assignees)) {
    return productDirection
      ? "assigned PR has active human signal"
      : "assigned PR has maintainer/human signal";
  }
  if (nonEmptyArray(requestedReviewers) || nonEmptyArray(requestedTeams)) {
    return "requested reviewers or teams indicate active review signal";
  }
  if (maintainerAssociatedEntries(comments).length > 0) {
    return productDirection
      ? "maintainer issue comment calibrates product direction"
      : "maintainer issue comment blocks low-signal auto-close";
  }
  if (maintainerAssociatedEntries(reviews).length > 0) {
    return productDirection
      ? "maintainer PR review calibrates product direction"
      : "maintainer PR review blocks low-signal auto-close";
  }
  if (productDirection && maintainerAssociatedEntries(reviewComments).length > 0) {
    return "maintainer inline review comment calibrates product direction";
  }
  return null;
}

function nonEmptyArray(value: JsonValue): boolean {
  return Array.isArray(value) && value.length > 0;
}

function maintainerAssociatedEntries(entries: JsonValue): JsonValue[] {
  if (!Array.isArray(entries)) return [];
  return entries.filter((entry) =>
    MAINTAINER_AUTHOR_ASSOCIATIONS.has(
      normalizeAuthorAssociation((entry as LooseRecord).author_association),
    ),
  );
}

function normalizedCloseKind(kind: JsonValue): RepositoryItemKind | null {
  const value = String(kind ?? "").trim();
  if (value === "issue" || value === "pull_request") return value;
  return null;
}

function trustedCloseRepositoryProfile(repo: JsonValue) {
  try {
    return repositoryProfileFor(String(repo ?? ""));
  } catch (error) {
    return error instanceof Error
      ? error.message
      : "trusted close target repository is unsupported";
  }
}

function trustedCloseBlockingProtectedLabels(labels: JsonValue, closeReason: JsonValue): string[] {
  const blocked = normalizedLabels(labels).filter(
    (label) => CLOSE_PROTECTED_LABEL_NAMES.some((name) => name === label) || isSecurityLabel(label),
  );
  if (!isVerifiedFixedCloseReason(closeReason)) return unique(blocked);
  return unique(blocked.filter((label) => label !== "maintainer"));
}

function trustedCloseUpdatedAtBlockReason({
  expectedItemUpdatedAt,
  currentItemUpdatedAt,
  expectedSourceRevision,
  currentSourceRevision,
  comments,
  sourceCommentId,
  trustedAuthors,
}: LooseRecord): string | null {
  const expectedMs = Date.parse(String(expectedItemUpdatedAt ?? ""));
  if (!Number.isFinite(expectedMs)) {
    return "trusted close marker must include the reviewed item updated_at timestamp";
  }
  const currentMs = Date.parse(String(currentItemUpdatedAt ?? ""));
  if (!Number.isFinite(currentMs)) return "live issue/PR updated_at could not be verified";
  if (currentMs <= expectedMs) return null;
  const expectedRevision = String(expectedSourceRevision ?? "").trim();
  const currentRevision = String(currentSourceRevision ?? "").trim();
  if (
    sourceCommentId &&
    Array.isArray(comments) &&
    comments.some((comment: JsonValue) =>
      isTrustedCloseReviewCommentChurn({
        comment,
        sourceCommentId,
        currentItemUpdatedAt,
        trustedAuthors,
      }),
    ) &&
    /^[a-f0-9]{64}$/i.test(expectedRevision) &&
    currentRevision === expectedRevision
  ) {
    return null;
  }
  if (expectedRevision && currentRevision && currentRevision !== expectedRevision) {
    return "source issue/PR changed since trusted close review";
  }
  return "live issue/PR updated_at changed since trusted close review";
}

function isTrustedCloseReviewCommentChurn({
  comment,
  sourceCommentId,
  currentItemUpdatedAt,
  trustedAuthors,
}: LooseRecord): boolean {
  if (String(comment?.id ?? "") !== String(sourceCommentId ?? "")) return false;
  const author = String(comment?.user?.login ?? "")
    .trim()
    .toLowerCase();
  const trusted = new Set(
    [...trustedAuthors].map((candidate: JsonValue) =>
      String(candidate ?? "")
        .trim()
        .toLowerCase(),
    ),
  );
  if (!trusted.has(author) && !isAutomationAuthor(author)) return false;
  return (
    String(comment?.updated_at ?? comment?.created_at ?? "") === String(currentItemUpdatedAt ?? "")
  );
}

export function normalizedLabels(labels: JsonValue): string[] {
  if (!Array.isArray(labels)) return [];
  return labels
    .map((label) =>
      String((label as LooseRecord)?.name ?? label)
        .trim()
        .toLowerCase(),
    )
    .filter(Boolean);
}

function isVerifiedFixedCloseReason(reason: JsonValue): boolean {
  return String(reason ?? "") === "implemented_on_main";
}

function normalizeAuthorAssociation(value: JsonValue): string {
  const normalized = String(value ?? "")
    .trim()
    .toUpperCase();
  return normalized || "NONE";
}

function nonAutomationActivityAfterReviewBlock({
  comments,
  reviewedAt,
  trustedAuthors,
}: LooseRecord): string | null {
  const reviewedAtMs = Date.parse(String(reviewedAt ?? ""));
  if (!Number.isFinite(reviewedAtMs))
    return "trusted close marker must include the reviewed item timestamp";
  if (!Array.isArray(comments)) return null;

  const trusted = new Set(
    [...trustedAuthors].map((author: JsonValue) =>
      String(author ?? "")
        .trim()
        .toLowerCase(),
    ),
  );
  const comment = comments.find((entry: JsonValue) => {
    const updatedAtMs = Date.parse(String(entry?.updated_at ?? entry?.created_at ?? ""));
    if (!Number.isFinite(updatedAtMs) || updatedAtMs <= reviewedAtMs) return false;
    const author = String(entry?.user?.login ?? "")
      .trim()
      .toLowerCase();
    return !trusted.has(author) && !isAutomationAuthor(author);
  });
  if (!comment) return null;
  const author = String(comment?.user?.login ?? "unknown author").trim() || "unknown author";
  return `non-automation activity after trusted close review by ${author}`;
}

function isAutomationAuthor(author: string): boolean {
  return (
    /(?:^|[-_])(bot|app)$|\[bot\]$/i.test(author) || /clawsweeper|github-actions/i.test(author)
  );
}

type AutoRepairDispatchEntry = {
  repo?: unknown;
  issue_number?: unknown;
  intent?: unknown;
  status?: unknown;
  target?: { head_sha?: unknown } | null;
  comment_updated_at?: unknown;
  actions?: readonly { action?: unknown; status?: unknown }[];
};

export function autoRepairHeadKey({
  repo,
  issueNumber,
  headSha,
}: {
  repo: unknown;
  issueNumber: unknown;
  headSha: unknown;
}) {
  const sha = String(headSha ?? "").trim();
  if (!sha) return null;
  return `${String(repo ?? "")}#${String(issueNumber ?? "")}:${sha}`;
}

export function autoRepairBlockReason({
  entries = [],
  plannedHeads = new Set<string>(),
  repo,
  issueNumber,
  headSha,
  maxRepairsPerPr,
  maxRepairsPerHead,
  resumeBoundary = 0,
}: {
  entries?: readonly AutoRepairDispatchEntry[];
  plannedHeads?: ReadonlySet<string>;
  repo: unknown;
  issueNumber: unknown;
  headSha: unknown;
  maxRepairsPerPr: number;
  maxRepairsPerHead: number;
  resumeBoundary?: unknown;
}) {
  const headKey = autoRepairHeadKey({ repo, issueNumber, headSha });
  if (!headKey) return null;

  const priorPrDispatches = entries.filter(
    (entry) =>
      isAutoRepairDispatchForPr(entry, repo, issueNumber) &&
      isAfterAutoRepairResumeBoundary(entry, resumeBoundary),
  );
  if (priorPrDispatches.length >= maxRepairsPerPr) {
    return `ClawSweeper auto repair already dispatched ${priorPrDispatches.length} total time(s) for this PR`;
  }

  if (plannedHeads.has(headKey)) {
    return "ClawSweeper auto repair already planned for this PR head in this scan";
  }

  const priorHeadDispatches = priorPrDispatches.filter(
    (entry) => String(entry.target?.head_sha ?? "") === String(headSha ?? ""),
  );
  if (priorHeadDispatches.length >= maxRepairsPerHead) {
    return `ClawSweeper auto repair already dispatched ${priorHeadDispatches.length} time(s) for this PR head`;
  }

  return null;
}

function isAutoRepairDispatchForPr(
  entry: AutoRepairDispatchEntry,
  repo: unknown,
  issueNumber: unknown,
) {
  const hasRepairDispatchAction = entry.actions?.some(
    (action) => action?.action === "dispatch_repair" && action?.status === "executed",
  );
  return (
    entry.repo === repo &&
    Number(entry.issue_number) === Number(issueNumber) &&
    entry.status === "executed" &&
    (entry.intent === "clawsweeper_auto_repair" || hasRepairDispatchAction)
  );
}

function isAfterAutoRepairResumeBoundary(entry: AutoRepairDispatchEntry, resumeBoundary: unknown) {
  const boundary = Number(resumeBoundary) || 0;
  if (!boundary) return true;
  const updatedAt = Date.parse(String(entry.comment_updated_at ?? "")) || 0;
  return updatedAt > boundary;
}


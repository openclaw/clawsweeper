function uniquePositiveIntegers(values: JsonValue): number[] {
  if (!Array.isArray(values)) return [];
  return [
    ...new Set(
      values
        .map((value: JsonValue) => Number(value))
        .filter((number: number) => Number.isInteger(number) && number > 0),
    ),
  ];
}


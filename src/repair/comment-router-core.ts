// Return why a PR cannot merge now, or "" when it is ready.
// Explicit maintainer approval resolves only the human-review and merge-ready pauses.
export function automergeReadinessBlockReason({
  command,
  view,
  target,
  comments,
  trustedAuthors,
  ledgerCommands,
}: {
  command: LooseRecord;
  view: LooseRecord;
  target: LooseRecord;
  comments: JsonValue;
  trustedAuthors: ReadonlySet<string>;
  ledgerCommands: JsonValue;
}): string {
  const labels = new Set(normalizedLabels(target?.labels));
  const approved =
    command.intent === "maintainer_approve_automerge" ||
    command.validated_maintainer_human_approval === true;
  if (labels.has(MANUAL_ONLY_LABEL)) return "PR is marked manual-only; merge is disabled";
  if (labels.has(AUTOGENERATED_LABEL))
    return "generated issue implementation PRs require manual merge";
  if (labels.has(AUTOFIX_LABEL)) return "PR is in ClawSweeper autofix mode; merge is disabled";
  if (!labels.has(AUTOMERGE_LABEL)) return "PR is not opted into ClawSweeper automerge";
  if (labels.has(HUMAN_REVIEW_LABEL) && !approved) return "PR is paused for human review";
  const blockedLabel = AUTOMERGE_BLOCKING_LABEL_NAMES.find((label) => {
    if (label === HUMAN_REVIEW_LABEL) return false;
    if (label === MERGE_READY_LABEL && approved) return false;
    return labels.has(label);
  });
  if (blockedLabel) return `protected or paused repair label: ${blockedLabel}`;
  if (view.state && view.state !== "OPEN")
    return `pull request is ${String(view.state).toLowerCase()}`;
  if (view.isDraft) return "pull request is draft";
  if (String(view.baseRefName ?? "") !== "main") return "pull request base is not main";
  const headBlock = reviewedHeadShaBlockReason({
    expectedHeadSha: command.expected_head_sha,
    currentHeadSha: view.headRefOid,
    markerName: "pass",
  });
  if (headBlock) return headBlock;
  if (view.mergeable !== "MERGEABLE") return `mergeable state is ${view.mergeable || "unknown"}`;
  const checks = summarizeChecks(view.statusCheckRollup ?? []);
  if (checks.terminalBlockers?.length > 0)
    return `checks are not green: ${checks.terminalBlockers.slice(0, 8).join(", ")}`;
  if (checks.pending?.length > 0)
    return `checks are still running: ${checks.pending.slice(0, 8).join(", ")}`;
  if (checks.total === 0) return "no PR checks found";
  const mergeStateStatus = String(view.mergeStateStatus ?? "");
  if (command.intent === "maintainer_approve_automerge" && mergeStateStatus === "BEHIND") {
    return "maintainer-approved PR head is behind base";
  }
  if (
    !isAutomergeMergeStateReady(mergeStateStatus) &&
    !(mergeStateStatus === "UNSTABLE" && checks.blockers.length === 0)
  ) {
    return `merge state status is ${view.mergeStateStatus || "unknown"}`;
  }
  if (["CHANGES_REQUESTED", "REVIEW_REQUIRED"].includes(String(view.reviewDecision ?? ""))) {
    return `review decision is ${view.reviewDecision}`;
  }
  // The exact-head review gate runs last, so repairable states above reach repair first.
  const review = latestTrustedExactHeadReview({
    comments: Array.isArray(comments) ? comments : [],
    headSha: String(view.headRefOid ?? ""),
    trustedAuthors,
  });
  if (!review) return "no trusted exact-head ClawSweeper review found";
  if (review.decision === "legacy") {
    return "exact-head ClawSweeper review uses a legacy marker without live verification state";
  }
  if (["failed", "malformed", "unknown"].includes(review.liveVerification)) {
    return `exact-head ClawSweeper review has ${review.liveVerification} live verification`;
  }
  const allowHumanApproval = maintainerApprovalAppliesToExactHeadReview({
    approvalValidated: command.validated_maintainer_human_approval === true,
    review,
    optInTime:
      command.trusted_bot !== true && approved
        ? (command.comment_updated_at ?? command.comment_created_at ?? 0)
        : latestRepairLoopResumeTime(ledgerCommands, command),
    replacementAutomergeRequestedBy: automergeRequestedByFromBody(target.body),
  });
  if (review.decision !== "pass" && !(allowHumanApproval && review.decision === "human")) {
    return `exact-head ClawSweeper review decision is ${review.decision}`;
  }
  return "";
}

function renderStatusBody(command: LooseRecord) {
  const target = command.target ?? {};
  const lines = ["ClawSweeper status:"];
  if (target.kind === "pull_request") {
    const labelState = automergeLabelState(target.labels ?? []);
    lines.push(`- Current PR: \`${command.issue_number ?? "unknown"}\``);
    lines.push(`- Branch: \`${target.branch ?? "unknown"}\``);
    lines.push(`- ClawSweeper PR: ${target.is_clawsweeper_pr ? "yes" : "no"}`);
    lines.push(`- Automerge: \`${labelState}\``);
    if (target.automerge_job_path) lines.push(`- Automerge job: \`${target.automerge_job_path}\``);
    if (target.job_path) lines.push(`- Job: \`${target.job_path}\``);
    if (target.merge_state_status) lines.push(`- Merge state: \`${target.merge_state_status}\``);
    if (target.review_decision) lines.push(`- Review decision: \`${target.review_decision}\``);
    lines.push(`- Checks: ${formatCounts(target.checks?.counts) || "none"}`);
    if (target.checks?.blockers?.length)
      lines.push(`- Check blockers: ${target.checks.blockers.slice(0, 5).join(", ")}`);
  } else {
    lines.push(`- Current issue: \`${command.issue_number ?? "unknown"}\``);
    lines.push(`- State: \`${target.state ?? "unknown"}\``);
    lines.push("- Existing PR repair: not applicable until a ClawSweeper PR exists.");
  }
  return lines.join("\n");
}

// The typed `hold` marker attribute selects the guidance. Do not pick it from reason prose.
function humanReviewGuidance(hold: JsonValue): { why: string; next: string } {
  const approveInstruction =
    "If the maintainer accepts the current risk and wants ClawSweeper to continue merge gates, comment `@clawsweeper approve`.";
  if (hold === "proof") {
    return {
      why: "The review did not find enough real behavior proof. A maintainer needs to decide whether the available proof is enough before automation continues.",
      next: [
        approveInstruction,
        "If proof is still missing, add redacted real behavior proof, then comment `@clawsweeper automerge` to re-review and continue.",
        `If automation should not continue, leave \`${HUMAN_REVIEW_LABEL}\` in place or comment \`@clawsweeper stop\`.`,
      ].join(" "),
    };
  }
  if (hold === "maintainer_decision") {
    return {
      why: "The review asks for a maintainer decision. ClawSweeper is keeping the item open so a maintainer can make the final choice.",
      next: [
        approveInstruction,
        "If the decision needs more evidence first, add it or resolve the maintainer-owned blocker, then comment `@clawsweeper automerge`.",
        "If the maintainer wants to own landing outside automation, merge manually after repository gates pass.",
      ].join(" "),
    };
  }
  if (hold === "security") {
    return {
      why: "The security review needs attention. ClawSweeper is pausing instead of making an autonomous change that could affect trust, credentials, permissions, or exposure.",
      next: [
        approveInstruction,
        "If the security-sensitive detail still needs changes, describe the safe path or push the fix, then comment `@clawsweeper automerge`.",
        "If the risk should not be automated, keep the PR paused for manual review or comment `@clawsweeper stop`.",
      ].join(" "),
    };
  }
  return {
    why: "ClawSweeper found a blocker that should be resolved or accepted by a maintainer before the repair or automerge loop continues.",
    next: [
      approveInstruction,
      "If more work is needed, resolve the blocker first, then comment `@clawsweeper automerge` to re-review and continue.",
      `If automation should stay paused, leave \`${HUMAN_REVIEW_LABEL}\` in place or comment \`@clawsweeper stop\`.`,
    ].join(" "),
  };
}

function automergeLabelState(labels: JsonValue[]) {
  const normalized = new Set(labels.map((value: JsonValue) => String(value).toLowerCase()));
  if (normalized.has(HUMAN_REVIEW_LABEL)) return "paused-human-review";
  if (normalized.has(MERGE_READY_LABEL)) return "merge-ready-human-gate";
  if (normalized.has(AUTOMERGE_LABEL)) return "enabled";
  if (normalized.has(AUTOFIX_LABEL)) return "autofix-only";
  return "not-enabled";
}

function formatCounts(counts: LooseRecord) {
  return Object.entries(counts ?? {})
    .map(([key, value]: JsonValue[]) => `${key}:${value}`)
    .join(" ");
}

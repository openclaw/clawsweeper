#!/usr/bin/env bash
set -euo pipefail

job_path="${JOB_PATH:-${CLUSTER_JOB_PATH:-}}"
job_name="${job_path##*/}"
allow_merge="${CLAWSWEEPER_REQUESTED_ALLOW_MERGE:-${CLAWSWEEPER_ALLOW_MERGE:-0}}"

normalize_yaml_scalar() {
  local value="$1"
  if [[ ${#value} -ge 2 ]]; then
    local first="${value:0:1}"
    local last="${value: -1}"
    if [[ "$first" == "$last" && ( "$first" == '"' || "$first" == "'" ) ]]; then
      value="${value:1:${#value}-2}"
    fi
  fi
  printf '%s' "$value"
}

if [[ ! -f "$job_path" ]]; then
  allow_merge=0
elif [[ "$job_name" == issue-*.md || "$job_name" == self-heal-*.md ]]; then
  allow_merge=0
elif [[ "$job_name" == automerge-*.md && "$allow_merge" == 1 ]]; then
  repair_mode="$(awk '
    /^---$/ { boundary += 1; if (boundary == 2) exit; next }
    boundary == 1 && $1 == "repair_mode:" {
      if (++count > 1) {
        print "Ambiguous duplicate repair_mode in repair job" > "/dev/stderr"
        exit 2
      }
      value = $2
    }
    END { if (count == 1) print value }
  ' "$job_path")"

  repair_mode="$(normalize_yaml_scalar "$repair_mode")"
  if [[ "$repair_mode" != automerge ]]; then
    allow_merge=0
    echo "::notice title=Repair-only merge gate::Merge disabled for ${repair_mode:-unclassified} PR repair."
  else
    repository="$(awk '
      /^---$/ { boundary += 1; if (boundary == 2) exit; next }
      boundary == 1 && $1 == "repo:" { print $2; exit }
    ' "$job_path")"
    repository="$(normalize_yaml_scalar "$repository")"
    pull_number="${job_path##*-}"
    pull_number="${pull_number%.md}"
    if ! [[ "$repository" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ && "$pull_number" =~ ^[1-9][0-9]*$ ]]; then
      echo "Invalid repair target: ${repository:-unknown}#${pull_number:-unknown}" >&2
      exit 1
    fi

    labels="$(gh api "repos/$repository/issues/$pull_number" --jq '.labels[]?.name' | tr '[:upper:]' '[:lower:]')"
    if ! printf '%s\n' "$labels" | grep -Fxq 'clawsweeper:automerge' ||
      printf '%s\n' "$labels" | grep -Eq '^(security|beta-blocker|release-blocker|maintainer|clawsweeper:(autofix|autogenerated|human-review|manual-only|merge-ready|needs-security-review|needs-maintainer-review|needs-product-decision))$'; then
      allow_merge=0
      echo "::notice title=Unauthorized PR merge::Merge requires an explicit automerge label and no protected or paused repair labels."
    fi
  fi
fi

{
  echo "allow_execute=${CLAWSWEEPER_ALLOW_EXECUTE:-0}"
  echo "allow_fix_pr=${CLAWSWEEPER_ALLOW_FIX_PR:-0}"
  echo "allow_merge=$allow_merge"
} >> "$GITHUB_OUTPUT"

echo "CLAWSWEEPER_ALLOW_MERGE=$allow_merge" >> "$GITHUB_ENV"

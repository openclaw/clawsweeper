#!/usr/bin/env bash
set -euo pipefail

JOB_PATH="${1:-${JOB_PATH:-}}"
SKIP_TARGET="${2:-this worker}"

if [ -z "$JOB_PATH" ]; then
  echo "JOB_PATH is required" >&2
  exit 1
fi

write_output() {
  local key="$1"
  local value="$2"
  if [ -n "${GITHUB_OUTPUT:-}" ]; then
    echo "$key=$value" >> "$GITHUB_OUTPUT"
  else
    echo "$key=$value"
  fi
}

parse_repair_job_path() {
  local kind="$1" filename stem rest
  filename="${JOB_PATH##*/}"
  stem="${filename%.md}"
  rest="${stem#${kind}-}"
  PARSED_JOB_NUMBER="${rest##*-}"
  PARSED_JOB_REPO_SLUG="${rest%-${PARSED_JOB_NUMBER}}"
  PARSED_JOB_OWNER="${JOB_PATH#jobs/}"
  PARSED_JOB_OWNER="${PARSED_JOB_OWNER%%/*}"
  PARSED_JOB_REPO_NAME="${PARSED_JOB_REPO_SLUG#${PARSED_JOB_OWNER}-}"
  if [ -z "$PARSED_JOB_NUMBER" ] || [ "$PARSED_JOB_NUMBER" = "$rest" ] || [ -z "$PARSED_JOB_REPO_NAME" ] || [ "$PARSED_JOB_REPO_NAME" = "$PARSED_JOB_REPO_SLUG" ]; then
    return 1
  fi
  PARSED_JOB_REPO="$PARSED_JOB_OWNER/$PARSED_JOB_REPO_NAME"
  PARSED_JOB_REF="#$PARSED_JOB_NUMBER"
  PARSED_JOB_BRANCH="clawsweeper/$kind-$PARSED_JOB_REPO_SLUG-$PARSED_JOB_NUMBER"
}

restore_automerge_job() {
  case "$JOB_PATH" in
    jobs/*/inbox/automerge-*.md) ;;
    *) return 1 ;;
  esac
  parse_repair_job_path automerge || return 1
  local number="$PARSED_JOB_NUMBER" repo_slug="$PARSED_JOB_REPO_SLUG" repo="$PARSED_JOB_REPO" ref="$PARSED_JOB_REF" branch="$PARSED_JOB_BRANCH" repair_mode labels merge_instruction
  repair_mode="autofix"
  merge_instruction="Final merge is disabled for autofix. Keep the PR open after a passing ClawSweeper verdict unless a maintainer explicitly changes mode."
  if [[ "${CLAWSWEEPER_REQUESTED_ALLOW_MERGE:-${CLAWSWEEPER_ALLOW_MERGE:-0}}" == 1 ]]; then
    if [[ -z "${GH_TOKEN:-}" ]]; then
      echo "A GitHub token is required to verify restored automerge authorization." >&2
      return 1
    fi
    if ! labels="$(gh api "repos/$repo/issues/$number" --jq '.labels[]?.name' | tr '[:upper:]' '[:lower:]')"; then
      echo "Unable to verify live authorization for restored repair job $repo#$number." >&2
      return 1
    fi
    if printf '%s\n' "$labels" | grep -Fxq 'clawsweeper:automerge' &&
      ! printf '%s\n' "$labels" | grep -Eq '^(security|beta-blocker|release-blocker|maintainer|clawsweeper:(autofix|autogenerated|human-review|manual-only|merge-ready|needs-security-review|needs-maintainer-review|needs-product-decision))$'; then
      repair_mode="automerge"
      merge_instruction="Do not merge, close, or bypass review gates from the worker. The comment router owns final merge only after a passing ClawSweeper verdict for the exact current head."
    fi
  fi
  mkdir -p "$(dirname "$JOB_PATH")"
  cat > "$JOB_PATH" <<EOF
---
repo: $repo
cluster_id: automerge-$repo_slug-$number
mode: autonomous
repair_mode: $repair_mode
allowed_actions:
  - comment
  - label
  - fix
  - raise_pr
blocked_actions:
  - close
  - merge
require_human_for:
  - close
  - merge
canonical:
  - $ref
candidates:
  - $ref
cluster_refs:
  - $ref
allow_instant_close: false
allow_fix_pr: true
allow_merge: false
allow_unmerged_fix_close: false
allow_post_merge_close: false
require_fix_before_close: true
security_policy: central_security_only
security_sensitive: false
target_branch: $branch
source: pr_automerge
---

# ClawSweeper adopted PR repair candidate

Maintainer opted $ref into ClawSweeper $repair_mode.

Source PR: https://github.com/$repo/pull/$number
Title: PR $ref

ClawSweeper should use this job only for the bounded ClawSweeper review/fix loop:

- If ClawSweeper emits an explicit repair marker, requests changes, or finds failing checks/rebase work, and the PR branch is safe to update, emit a fix artifact with \`repair_strategy: "repair_contributor_branch"\` and \`source_prs: ["https://github.com/$repo/pull/$number"]\`.
- If the PR branch cannot be safely updated, emit a narrow credited replacement only when the artifact can preserve the original contributor credit; otherwise return \`needs_human\`.
- $merge_instruction
- Keep repair scope limited to actionable ClawSweeper findings, failing relevant checks, and required review feedback on this PR.
EOF
}

restore_issue_implementation_job() {
  case "$JOB_PATH" in
    jobs/*/inbox/issue-*.md) ;;
    *) return 1 ;;
  esac
  parse_repair_job_path issue || return 1
  local number="$PARSED_JOB_NUMBER" repo_slug="$PARSED_JOB_REPO_SLUG" repo="$PARSED_JOB_REPO" ref="$PARSED_JOB_REF" branch="$PARSED_JOB_BRANCH"
  mkdir -p "$(dirname "$JOB_PATH")"
  cat > "$JOB_PATH" <<EOF
---
repo: $repo
cluster_id: issue-$repo_slug-$number
mode: autonomous
allowed_actions:
  - comment
  - label
  - fix
  - raise_pr
blocked_actions:
  - close
  - merge
require_human_for:
  - close
  - merge
canonical:
  - $ref
candidates:
  - $ref
cluster_refs:
  - $ref
allow_instant_close: false
allow_fix_pr: true
allow_merge: false
allow_unmerged_fix_close: false
allow_post_merge_close: false
require_fix_before_close: false
security_policy: central_security_only
security_sensitive: false
target_branch: $branch
source: issue_implementation
required_pr_labels:
  - clawsweeper:autogenerated
---

# ClawSweeper issue implementation candidate

ClawSweeper Repair should create or update one implementation PR from \`$branch\`.

Source issue: https://github.com/$repo/issues/$number
Title: Issue $ref

## Operator Prompt

Use the source issue as the product request or bug report. Verify the request is still valid on latest \`$repo@main\`, inspect nearby code, and make the narrowest implementation that directly satisfies the issue. If the issue is too broad, underspecified, security-sensitive, already fixed, or not safely implementable by automation, do not change code; report the exact blocker.

When code changes are appropriate, emit a fix artifact with \`repair_strategy: "new_fix_pr"\`, \`source_prs: []\`, this issue in \`linked_refs\`, and validation commands for the touched surface.

## Guardrails

- Do not merge.
- Do not close the issue from this lane.
- Keep one PR for this issue; reuse \`$branch\` if it already exists.
- Keep the diff narrow and avoid unrelated refactors.
- Preserve issue context and link https://github.com/$repo/issues/$number in the PR body.
- Add a changelog entry when the target repo expects one.
EOF
}

restore_self_heal_job() {
  case "$JOB_PATH" in
    jobs/*/inbox/self-heal-*.md) ;;
    *) return 1 ;;
  esac
  parse_repair_job_path self-heal || return 1
  local number="$PARSED_JOB_NUMBER" repo_slug="$PARSED_JOB_REPO_SLUG" repo="$PARSED_JOB_REPO" ref="$PARSED_JOB_REF" branch="$PARSED_JOB_BRANCH"
  mkdir -p "$(dirname "$JOB_PATH")"
  cat > "$JOB_PATH" <<EOF
---
repo: $repo
cluster_id: self-heal-$repo_slug-$number
mode: autonomous
job_intent: clawsweeper_self_rebase
allowed_actions:
  - comment
  - fix
blocked_actions:
  - close
  - merge
  - label
require_human_for:
  - close
  - merge
canonical:
  - $ref
candidates:
  - $ref
cluster_refs:
  - $ref
allow_instant_close: false
allow_fix_pr: true
allow_merge: false
allow_unmerged_fix_close: false
allow_post_merge_close: false
require_fix_before_close: true
security_policy: central_security_only
security_sensitive: false
target_branch: $branch
source: clawsweeper_self_rebase
self_heal_target_pr: "$number"
expected_head_sha: "unknown"
self_heal_merge_state: "restored missing self-heal job"
---

# ClawSweeper self-heal PR rebase

This restored placeholder cannot safely mutate because the original target head SHA is unavailable.
The self-heal exact-head verifier will skip this job unless the durable state file is restored with a concrete expected_head_sha.
EOF
}

if [ -f "$JOB_PATH" ]; then
  write_output job_exists 1
elif [[ "$JOB_PATH" == jobs/*/inbox/automerge-*.md ]]; then
  if ! restore_automerge_job; then
    echo "Refusing to restore an unverified automerge repair job: $JOB_PATH" >&2
    exit 1
  fi
  write_output job_exists 1
  echo "::notice title=Restored automerge repair job::Job file '$JOB_PATH' was missing from the state checkout; reconstructed it from the workflow input."
elif restore_issue_implementation_job; then
  write_output job_exists 1
  echo "::notice title=Restored issue implementation job::Job file '$JOB_PATH' was missing from the state checkout; reconstructed it from the workflow input."
elif restore_self_heal_job; then
  write_output job_exists 1
  echo "::notice title=Restored self-heal repair job::Job file '$JOB_PATH' was missing from the state checkout; reconstructed a non-mutating placeholder from the workflow input."
else
  write_output job_exists 0
  echo "::notice title=Stale repair dispatch::Job file '$JOB_PATH' no longer exists on the current state checkout; skipping $SKIP_TARGET."
fi

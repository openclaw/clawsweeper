import assert from "node:assert/strict";
import test from "node:test";

import {
  AUTOFIX_LABEL,
  AUTOGENERATED_LABEL,
  AUTOMERGE_LABEL,
  BULK_FILED_LABEL,
  CLOSE_PROTECTED_LABEL_NAMES,
  HUMAN_REVIEW_LABEL,
  MANUAL_ONLY_LABEL,
  MERGE_READY_LABEL,
  NEEDS_SECURITY_REVIEW_LABEL,
  SECURITY_BOUNDARY_MERGE_RISK_LABEL,
} from "../../dist/repair/exact-review-guard-labels.js";
import { issueSourceRevisionSha256 } from "../../dist/repair/issue-source-guard.js";

const issue = {
  number: 244,
  state: "open",
  locked: false,
  title: "Add reviewed behavior",
  body: "Implement the narrow reviewed request.",
  labels: [{ name: "enhancement" }],
};

test("source issue revision ignores ClawSweeper comments but tracks human edits", () => {
  const botComment = {
    id: 1,
    user: { login: "clawsweeper[bot]" },
    body: "review v1",
    updated_at: "2026-06-11T10:00:00Z",
  };
  const humanComment = {
    id: 2,
    user: { login: "maintainer" },
    body: "keep this narrow",
    updated_at: "2026-06-11T10:01:00Z",
  };
  const revision = issueSourceRevisionSha256(issue, [botComment, humanComment]);

  assert.equal(
    issueSourceRevisionSha256(issue, [
      { ...botComment, body: "review v2", updated_at: "2026-06-11T10:02:00Z" },
      humanComment,
    ]),
    revision,
  );
  assert.notEqual(
    issueSourceRevisionSha256(issue, [
      botComment,
      { ...humanComment, body: "expanded request", updated_at: "2026-06-11T10:03:00Z" },
    ]),
    revision,
  );
});

test("source issue revision ignores automation labels but tracks human labels", () => {
  const revision = issueSourceRevisionSha256(issue, []);
  const automationLabels = [
    "status: ⏳ waiting on author",
    "rating: 🧂 unranked krab",
    "proof: sufficient",
    "merge-risk: 🚨 automation",
    "impact:message-loss",
    "impact:security",
    SECURITY_BOUNDARY_MERGE_RISK_LABEL,
    NEEDS_SECURITY_REVIEW_LABEL,
    "issue-rating: 🦪 silver shellfish",
    "P1",
    "maturity:stable",
    "feature: ✨ showcase",
    "good first issue",
    "mantis: telegram-visible-proof",
    "proof: telegram-e2e",
    "triage: needs-real-behavior-proof",
    "clawsweeper:reviewed",
    AUTOGENERATED_LABEL,
    AUTOFIX_LABEL,
    AUTOMERGE_LABEL,
    MERGE_READY_LABEL,
    "no-stale",
    "stale",
  ];

  for (const name of automationLabels) {
    assert.equal(
      issueSourceRevisionSha256({ ...issue, labels: [...issue.labels, { name }] }, []),
      revision,
      name,
    );
  }
  for (const name of [
    "needs-design",
    ...CLOSE_PROTECTED_LABEL_NAMES.filter((name) => !automationLabels.includes(name)),
    HUMAN_REVIEW_LABEL,
    MANUAL_ONLY_LABEL,
    BULK_FILED_LABEL,
  ]) {
    assert.notEqual(
      issueSourceRevisionSha256({ ...issue, labels: [...issue.labels, { name }] }, []),
      revision,
      name,
    );
  }
});

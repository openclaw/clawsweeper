type Workflow = {
  jobs?: Record<
    string,
    {
      env?: Record<string, string>;
      steps?: Array<{
        name?: string;
        run?: string;
        env?: Record<string, string>;
        uses?: string;
        with?: Record<string, string>;
      }>;
    }
  >;
};

test("cluster worker passes workflow inputs through environment boundaries", () => {
  const source = fs.readFileSync(".github/workflows/repair-cluster-worker.yml", "utf8");
  const workflow = parse(source) as Workflow;
  for (const [jobName, job] of Object.entries(workflow.jobs ?? {})) {
    for (const step of job.steps ?? []) {
      if (typeof step.run !== "string") continue;
      assert.doesNotMatch(
        step.run,
        /\$\{\{\s*inputs\./,
        `${jobName}/${step.name ?? "unnamed"} interpolates an input into shell source`,
      );
    }
  }
  assert.match(source, /job_auth:[\s\S]*Materializer HMAC/);
  assert.equal(source.match(/run: pnpm run repair:restore-cluster-intake-job/g)?.length, 3);
  assert.equal(source.match(/CLAWSWEEPER_WEBHOOK_SECRET: \$\{\{ secrets\./g)?.length, 4);
  assert.ok(
    source.indexOf("Authenticate durable intake before credentials") <
      source.indexOf("Create GitHub App token"),
  );
  assert.doesNotMatch(source, /restore-durable-intake-job\.sh/);
});

test("generated issue workers can create PRs but never inherit the maintainer merge gate", () => {
  const workflow = parse(
    fs.readFileSync(".github/workflows/repair-cluster-worker.yml", "utf8"),
  ) as Workflow;

  for (const jobName of ["cluster", "execute"]) {
    const expression =
      workflow.jobs?.[jobName]?.env?.CLAWSWEEPER_REQUESTED_ALLOW_MERGE ??
      workflow.jobs?.[jobName]?.env?.CLAWSWEEPER_ALLOW_MERGE;
    assert.ok(expression, `${jobName} is missing an explicit merge gate`);
    assert.match(expression, /!contains\(inputs\.job, '\/inbox\/issue-'\)/);
    assert.match(expression, /\|\| '0'/);
  }
  assert.equal(workflow.jobs?.cluster?.env?.CLAWSWEEPER_ALLOW_MERGE, "0");

  assert.match(
    workflow.jobs?.execute?.env?.CLAWSWEEPER_OPENCLAW_MODEL ?? "",
    /CLAWSWEEPER_FIX_PR_MODEL \|\| 'gpt-5\.6-sol'/,
  );
  assert.match(
    workflow.jobs?.execute?.env?.CLAWSWEEPER_CODEX_REASONING_EFFORT ?? "",
    /CLAWSWEEPER_FIX_PR_REASONING_EFFORT \|\| 'xhigh'/,
  );
});

test("repair execution fails closed for autofix and autogenerated PRs", () => {
  const temporary = fs.mkdtempSync(path.join(tmpdir(), "clawsweeper-repair-gates-"));
  const jobPath = path.join(temporary, "jobs/openclaw/inbox/automerge-openclaw-openclaw-117144.md");
  const bin = path.join(temporary, "bin");
  const output = path.join(temporary, "github-output");
  const environment = path.join(temporary, "github-env");
  const ghCalls = path.join(temporary, "gh-calls");
  fs.mkdirSync(path.dirname(jobPath), { recursive: true });
  fs.mkdirSync(bin);
  const gh = path.join(bin, "gh");
  fs.writeFileSync(
    gh,
    '#!/usr/bin/env bash\nprintf invoked >> "$FAKE_GH_CALLS"\nprintf "%s\\n" "$FAKE_GH_LABELS"\n',
  );
  fs.chmodSync(gh, 0o755);

  const runGate = (repairMode: string | undefined, labels = "", relativePath?: string) => {
    const currentPath = relativePath ? path.join(temporary, relativePath) : jobPath;
    const modeLine = repairMode ? `repair_mode: ${repairMode}\n` : "";
    fs.mkdirSync(path.dirname(currentPath), { recursive: true });
    fs.writeFileSync(currentPath, `---\nrepo: openclaw/openclaw\n${modeLine}---\n`);
    fs.writeFileSync(output, "");
    fs.writeFileSync(environment, "");
    fs.rmSync(ghCalls, { force: true });
    const result = spawnSync("bash", ["scripts/capture-repair-execution-gates.sh"], {
      cwd: process.cwd(),
      encoding: "utf8",
      env: {
        ...process.env,
        PATH: `${bin}${path.delimiter}${process.env.PATH}`,
        JOB_PATH: currentPath,
        GITHUB_OUTPUT: output,
        GITHUB_ENV: environment,
        CLAWSWEEPER_ALLOW_EXECUTE: "1",
        CLAWSWEEPER_ALLOW_FIX_PR: "1",
        CLAWSWEEPER_ALLOW_MERGE: "1",
        FAKE_GH_CALLS: ghCalls,
        FAKE_GH_LABELS: labels,
      },
    });
    assert.equal(result.status, 0, result.stderr);
    return {
      output: fs.readFileSync(output, "utf8"),
      environment: fs.readFileSync(environment, "utf8"),
      calledGitHub: fs.existsSync(ghCalls),
    };
  };

  try {
    const autofix = runGate("autofix");
    assert.match(autofix.output, /^allow_merge=0$/m);
    assert.match(autofix.environment, /^CLAWSWEEPER_ALLOW_MERGE=0$/m);
    assert.equal(autofix.calledGitHub, false);

    const missingMode = runGate(undefined);
    assert.match(missingMode.output, /^allow_merge=0$/m);
    assert.equal(missingMode.calledGitHub, false);

    const generated = runGate("automerge", "clawsweeper:autogenerated");
    assert.match(generated.output, /^allow_merge=0$/m);
    assert.equal(generated.calledGitHub, true);

    const mislabeledAutofix = runGate("automerge", "clawsweeper:autofix");
    assert.match(mislabeledAutofix.output, /^allow_merge=0$/m);

    const missingAuthorization = runGate("automerge", "size: M");
    assert.match(missingAuthorization.output, /^allow_merge=0$/m);

    for (const pauseLabel of [
      "clawsweeper:human-review",
      "clawsweeper:manual-only",
      "clawsweeper:merge-ready",
      "ClawSweeper:Human-Review",
      "ClawSweeper:Manual-Only",
      "ClawSweeper:AutoFix",
      "ClawSweeper:Autogenerated",
      "security",
      "Security",
      "beta-blocker",
      "release-blocker",
      "maintainer",
      "clawsweeper:needs-security-review",
      "ClawSweeper:Needs-Security-Review",
      "clawsweeper:needs-maintainer-review",
      "clawsweeper:needs-product-decision",
    ]) {
      const paused = runGate("automerge", `clawsweeper:automerge\n${pauseLabel}`);
      assert.match(paused.output, /^allow_merge=0$/m, pauseLabel);
    }

    for (const label of ["clawsweeper:automerge", "ClawSweeper:AutoMerge"]) {
      const authorized = runGate("automerge", label);
      assert.match(authorized.output, /^allow_merge=1$/m);
      assert.match(authorized.environment, /^CLAWSWEEPER_ALLOW_MERGE=1$/m);
    }

    for (const quote of ['"', "'"]) {
      fs.writeFileSync(
        jobPath,
        `---\nrepo: ${quote}openclaw/openclaw${quote}\nrepair_mode: ${quote}automerge${quote}\n---\n`,
      );
      fs.writeFileSync(output, "");
      fs.writeFileSync(environment, "");
      const quoted = spawnSync("bash", ["scripts/capture-repair-execution-gates.sh"], {
        cwd: process.cwd(),
        encoding: "utf8",
        env: {
          ...process.env,
          PATH: `${bin}${path.delimiter}${process.env.PATH}`,
          JOB_PATH: jobPath,
          GITHUB_OUTPUT: output,
          GITHUB_ENV: environment,
          CLAWSWEEPER_ALLOW_MERGE: "1",
          FAKE_GH_CALLS: ghCalls,
          FAKE_GH_LABELS: "clawsweeper:automerge",
        },
      });
      assert.equal(quoted.status, 0, quoted.stderr);
      assert.match(fs.readFileSync(output, "utf8"), /^allow_merge=1$/m);
    }

    for (const directory of ["", "outbox/finalized/", "outbox/stuck/"]) {
      const legacyIssue = runGate(
        undefined,
        "",
        `jobs/openclaw/${directory}issue-openclaw-openclaw-117144.md`,
      );
      assert.match(legacyIssue.output, /^allow_merge=0$/m, directory);
      assert.equal(legacyIssue.calledGitHub, false);

      const legacyAutofix = runGate(
        "autofix",
        "clawsweeper:automerge",
        `jobs/openclaw/${directory}automerge-openclaw-openclaw-117144.md`,
      );
      assert.match(legacyAutofix.output, /^allow_merge=0$/m, directory);
      assert.equal(legacyAutofix.calledGitHub, false);
    }

    const selfHeal = runGate(
      undefined,
      "",
      "jobs/openclaw/outbox/finalized/self-heal-openclaw-openclaw-117144.md",
    );
    assert.match(selfHeal.output, /^allow_merge=0$/m);

    for (const unknownJob of [
      "jobs/openclaw/cluster-001.md",
      "jobs/openclaw/inbox/gitcrawl-42-feature+patch.md",
      "jobs/openclaw/outbox/stuck/cluster-002.md",
    ]) {
      const unknown = runGate("automerge", "clawsweeper:automerge", unknownJob);
      assert.match(unknown.output, /^allow_merge=0$/m, unknownJob);
      assert.equal(unknown.calledGitHub, false, unknownJob);
    }

    fs.rmSync(jobPath);
    fs.writeFileSync(output, "");
    fs.writeFileSync(environment, "");
    const archivedMissing = spawnSync("bash", ["scripts/capture-repair-execution-gates.sh"], {
      cwd: process.cwd(),
      encoding: "utf8",
      env: {
        ...process.env,
        JOB_PATH: jobPath,
        GITHUB_OUTPUT: output,
        GITHUB_ENV: environment,
        CLAWSWEEPER_ALLOW_MERGE: "1",
      },
    });
    assert.equal(archivedMissing.status, 0, archivedMissing.stderr);
    assert.match(fs.readFileSync(output, "utf8"), /^allow_merge=0$/m);

    fs.writeFileSync(
      jobPath,
      "---\nrepo: openclaw/openclaw\nrepair_mode: automerge\nrepair_mode: autofix\n---\n",
    );
    const ambiguous = spawnSync("bash", ["scripts/capture-repair-execution-gates.sh"], {
      cwd: process.cwd(),
      encoding: "utf8",
      env: {
        ...process.env,
        PATH: `${bin}${path.delimiter}${process.env.PATH}`,
        JOB_PATH: jobPath,
        GITHUB_OUTPUT: output,
        GITHUB_ENV: environment,
        CLAWSWEEPER_ALLOW_MERGE: "1",
        FAKE_GH_CALLS: ghCalls,
        FAKE_GH_LABELS: "clawsweeper:automerge",
      },
    });
    assert.notEqual(ambiguous.status, 0);
    assert.match(ambiguous.stderr, /duplicate repair_mode/);
  } finally {
    fs.rmSync(temporary, { recursive: true, force: true });
  }
});

test("repair workflow applies the fail-closed merge gate before worker execution", () => {
  const workflow = parse(
    fs.readFileSync(".github/workflows/repair-cluster-worker.yml", "utf8"),
  ) as Workflow;
  const capture = workflow.jobs?.cluster?.steps?.find(
    (step) => step.name === "Capture execution gates",
  );
  assert.equal(capture?.run, "bash scripts/capture-repair-execution-gates.sh");
  assert.deepEqual(capture?.env, { GH_TOKEN: "${{ steps.app_token.outputs.token }}" });

  const executionCapture = workflow.jobs?.execute?.steps?.find(
    (step) => step.name === "Recheck execution merge authorization",
  );
  assert.equal(executionCapture?.run, "bash scripts/capture-repair-execution-gates.sh");
  assert.deepEqual(executionCapture?.env, {
    GH_TOKEN: "${{ steps.target_write_token.outputs.token }}",
  });
  assert.ok(
    (workflow.jobs?.execute?.steps?.indexOf(executionCapture!) ?? -1) <
      (workflow.jobs?.execute?.steps?.findIndex(
        (step) => step.name === "Post-flight finalize fix PRs",
      ) ?? -1),
  );
});

test("missing PR repair jobs preserve only live authorized automerge", () => {
  const temporary = fs.mkdtempSync(path.join(tmpdir(), "clawsweeper-restore-mode-"));
  const relativeJobPath = "jobs/openclaw/inbox/automerge-openclaw-openclaw-123.md";
  const jobPath = path.join(temporary, relativeJobPath);
  const bin = path.join(temporary, "bin");
  const output = path.join(temporary, "github-output");
  fs.mkdirSync(bin, { recursive: true });
  fs.writeFileSync(
    path.join(bin, "gh"),
    '#!/usr/bin/env bash\nif [[ "${FAKE_GH_FAIL:-0}" == 1 ]]; then echo "HTTP 403 forbidden" >&2; exit 42; fi\nprintf "%s\\n" "$FAKE_GH_LABELS"\n',
    { mode: 0o755 },
  );

  const restore = (labels: string, allowMerge = "1") => {
    fs.rmSync(jobPath, { force: true });
    fs.writeFileSync(output, "");
    const result = spawnSync(
      "bash",
      [path.join(process.cwd(), "scripts/restore-repair-job.sh"), relativeJobPath],
      {
        cwd: temporary,
        encoding: "utf8",
        env: {
          ...process.env,
          PATH: `${bin}${path.delimiter}${process.env.PATH}`,
          GH_TOKEN: "test-app-token",
          GITHUB_OUTPUT: output,
          CLAWSWEEPER_REQUESTED_ALLOW_MERGE: allowMerge,
          FAKE_GH_LABELS: labels,
        },
      },
    );
    assert.equal(result.status, 0, result.stderr);
    assert.match(fs.readFileSync(output, "utf8"), /^job_exists=1$/m);
    return fs.readFileSync(jobPath, "utf8");
  };

  try {
    assert.match(restore("clawsweeper:automerge"), /^repair_mode: automerge$/m);
    assert.match(restore("clawsweeper:automerge\nclawsweeper:autofix"), /^repair_mode: autofix$/m);
    assert.match(restore("clawsweeper:automerge\nSecurity"), /^repair_mode: autofix$/m);
    assert.match(
      restore("clawsweeper:automerge\nClawSweeper:Needs-Maintainer-Review"),
      /^repair_mode: autofix$/m,
    );
    assert.match(restore("clawsweeper:automerge", "0"), /^repair_mode: autofix$/m);

    fs.rmSync(jobPath);
    fs.writeFileSync(output, "");
    const failedLookup = spawnSync(
      "bash",
      [path.join(process.cwd(), "scripts/restore-repair-job.sh"), relativeJobPath],
      {
        cwd: temporary,
        encoding: "utf8",
        env: {
          ...process.env,
          PATH: `${bin}${path.delimiter}${process.env.PATH}`,
          GH_TOKEN: "test-app-token",
          GITHUB_OUTPUT: output,
          CLAWSWEEPER_REQUESTED_ALLOW_MERGE: "1",
          FAKE_GH_FAIL: "1",
        },
      },
    );
    assert.notEqual(failedLookup.status, 0);
    assert.match(failedLookup.stderr, /Unable to verify live authorization/);
    assert.equal(fs.existsSync(jobPath), false);
    assert.doesNotMatch(fs.readFileSync(output, "utf8"), /^job_exists=1$/m);
  } finally {
    fs.rmSync(temporary, { recursive: true, force: true });
  }
});

test("repair jobs hydrate exactly their issue or pull-request record", () => {
  const workflow = parse(
    fs.readFileSync(".github/workflows/repair-cluster-worker.yml", "utf8"),
  ) as Workflow;
  const temporary = fs.mkdtempSync(path.join(tmpdir(), "clawsweeper-repair-target-"));
  const output = path.join(temporary, "github-output");

  const resolveTarget = (jobPath: string) => {
    fs.writeFileSync(output, "");
    const result = spawnSync("bash", ["scripts/resolve-repair-job-target.sh"], {
      cwd: process.cwd(),
      encoding: "utf8",
      env: { ...process.env, JOB_PATH: jobPath, GITHUB_OUTPUT: output },
    });
    return { ...result, output: fs.readFileSync(output, "utf8") };
  };

  try {
    for (const jobName of ["cluster", "execute"]) {
      const steps = workflow.jobs?.[jobName]?.steps ?? [];
      const resolve = steps.find((step) => step.name === "Resolve target owner");
      const hydrate = steps.find((step) => step.uses === "./.github/actions/setup-state");
      assert.equal(resolve?.run, "bash scripts/resolve-repair-job-target.sh");
      assert.equal(
        hydrate?.with?.["records-item-number"],
        "${{ steps.target.outputs.records_item_number || '' }}",
      );
    }

    const issue = resolveTarget("jobs/openclaw/inbox/issue-openclaw-openclaw-98276.md");
    assert.equal(issue.status, 0, issue.stderr);
    assert.match(issue.output, /^target_slug=openclaw-openclaw$/m);
    assert.match(issue.output, /^records_item_number=98276$/m);

    const pullRequest = resolveTarget("jobs/openclaw/inbox/automerge-openclaw-openclaw-117144.md");
    assert.equal(pullRequest.status, 0, pullRequest.stderr);
    assert.match(pullRequest.output, /^target_slug=openclaw-openclaw$/m);
    assert.match(pullRequest.output, /^records_item_number=117144$/m);

    const selfHeal = resolveTarget("jobs/openclaw/inbox/self-heal-openclaw-openclaw-117144.md");
    assert.equal(selfHeal.status, 0, selfHeal.stderr);
    assert.match(selfHeal.output, /^target_slug=openclaw-openclaw$/m);
    assert.match(selfHeal.output, /^records_item_number=117144$/m);

    for (const legacy of [
      "jobs/openclaw/cluster-001.md",
      "jobs/openclaw/outbox/finalized/cluster-001.md",
      "jobs/openclaw/outbox/stuck/cluster-002.md",
      "jobs/openclaw/inbox/gitcrawl-42-feature+patch.md",
    ]) {
      const result = resolveTarget(legacy);
      assert.equal(result.status, 0, result.stderr);
      assert.match(result.output, /^target_owner=openclaw$/m);
      assert.doesNotMatch(result.output, /^records_item_number=/m);
    }

    for (const invalid of [
      "jobs/openclaw/inbox/automerge-openclaw-openclaw-0.md",
      "jobs/openclaw/inbox/automerge-other-openclaw-117144.md",
      "jobs/openclaw/inbox/issue-openclaw-open@claw-98276.md",
      "jobs/openclaw/inbox/automerge-openclaw-openclaw-9007199254740992.md",
      "jobs/openclaw/../inbox/automerge-openclaw-openclaw-117144.md",
      "outside/openclaw/inbox/automerge-openclaw-openclaw-117144.md",
    ]) {
      const result = resolveTarget(invalid);
      assert.notEqual(result.status, 0, invalid);
    }
  } finally {
    fs.rmSync(temporary, { recursive: true, force: true });
  }
});

test("single-item comment commands avoid hydrating the full repository", () => {
  const workflow = parse(
    fs.readFileSync(".github/workflows/repair-comment-router.yml", "utf8"),
  ) as Workflow;
  const steps = workflow.jobs?.["route-comments"]?.steps ?? [];
  const resolve = steps.find((step) => step.name === "Resolve target repository");
  const hydrate = steps.find((step) => step.uses === "./.github/actions/setup-state");
  const temporary = fs.mkdtempSync(path.join(tmpdir(), "clawsweeper-comment-target-"));
  const output = path.join(temporary, "github-output");

  assert.ok(resolve?.run);
  assert.match(resolve.env?.ITEM_NUMBERS ?? "", /github\.event\.client_payload\.item_number/);
  assert.match(resolve.env?.ITEM_NUMBERS ?? "", /inputs\.item_numbers/);
  assert.equal(
    hydrate?.with?.["records-item-number"],
    "${{ steps.target.outputs.records_item_number || '' }}",
  );

  try {
    for (const [items, expected] of [
      ["117144", "117144"],
      ["9007199254740991", "9007199254740991"],
      ["9007199254740992", null],
      ["999999999999999999999999999", null],
      ["117144,117145", null],
      ["00117144", null],
      ["", null],
    ] as const) {
      fs.writeFileSync(output, "");
      const result = spawnSync("bash", ["-c", resolve.run], {
        cwd: process.cwd(),
        encoding: "utf8",
        env: {
          ...process.env,
          TARGET_REPO: "openclaw/openclaw",
          ITEM_NUMBERS: items,
          GITHUB_OUTPUT: output,
        },
      });
      assert.equal(result.status, 0, result.stderr);
      const actual = /^records_item_number=(.+)$/m.exec(fs.readFileSync(output, "utf8"))?.[1];
      assert.equal(actual ?? null, expected);
    }
  } finally {
    fs.rmSync(temporary, { recursive: true, force: true });
  }
});

